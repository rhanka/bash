#!/usr/bin/env node
// Generates dependency-free JavaScript bindings for a component with jco-transpile.
// Usage: node tools/transpile.mjs <component.wasm> <out-dir>
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { toolsDir } from "./lib.mjs";

export const JCO_VERSION = "0.24.0";

export async function transpileComponent(componentPath, outDir, { minify = false } = {}) {
  const pkg = join(toolsDir(), "npm", "node_modules", "@bytecodealliance", "jco-transpile");
  if (JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version !== JCO_VERSION) {
    throw new Error("unexpected jco-transpile version, expected " + JCO_VERSION);
  }
  const entry = join(pkg, "dist", "index.js");
  const { transpile } = await import(pathToFileURL(entry).href);
  const name = basename(componentPath).replace(/\.component\.wasm$/, "").replace(/\.wasm$/, "");
  const result = await transpile(resolve(componentPath), {
    name,
    instantiation: "sync",
    base64Cutoff: 0,
    validLiftingOptimization: true,
    tlaCompat: false,
    minify,
    wasiShim: false,
    nodejsCompat: false,
    optimize: false,
  });
  if (result.imports.length !== 0) throw new Error(`component has imports: ${result.imports.join(", ")}`);
  if (name === "kernel" || name === "kernel-test") {
    const glue = Buffer.from(result.files[name + ".js"]).toString("utf8");
    result.files[name + ".js"] = guardPromisingProbes(glue, { minify });
  }
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  writeFiles(outDir, result.files);
  embedShims(outDir, name);
  return readdirSync(outDir).sort();
}

// jco-transpile 0.24.0 probes synchronous canonical ABI helpers and discards the wrapper.
// On engines without JSPI, skip the call so the generator does not catch 14 TypeErrors.
export function guardPromisingProbes(source, { minify = false } = {}) {
  const drift = (detail) => new Error(`jco promising probe drift in kernel.js: ${detail}. Review the generated glue and update the guard`);
  const count = [...source.matchAll(/\bpromising\b/g)].length;
  if (count !== 14) throw drift(`expected 14 references, found ${count}`);

  // The minifier aliases the WebAssembly instance and uses backticks for export names.
  const alias = minify
    ? "let r=n?.shim?.globals?.WebAssembly??globalThis.WebAssembly;"
    : "\n\tlet WebAssembly = options?.shim?.globals?.WebAssembly ?? globalThis.WebAssembly;\n";
  if (!source.includes(alias)) {
    throw drift("WebAssembly alias changed");
  }
  const postReturn = minify
    ? /try\{r\.promising\((n\[`cabi_post_[^`\n]+`\])\)\}catch\{\1\}/g
    : /\n\t\ttry \{\n\t\t\tWebAssembly\.promising\((exports1\["cabi_post_[^"\n]+"\])\);\n\t\t\} catch \{\n\t\t\t\1;\n\t\t\}/g;
  const realloc = minify
    ? /try\{r\.promising\(n\.cabi_realloc\)\}catch\{\}/g
    : /\n\t\ttry \{\n\t\t\tWebAssembly\.promising\(exports1\.cabi_realloc\);\n\t\t\} catch \{\}/g;
  for (const [pattern, expected, kind] of [[postReturn, 13, "post-return"], [realloc, 1, "realloc"]]) {
    const matches = [...source.matchAll(pattern)].length;
    if (matches !== expected) throw drift(`expected ${expected} ${kind} probes in the pinned try/catch shape, found ${matches}`);
    source = source.replace(pattern, (probe) => probe.replace(".promising(", ".promising?.("));
  }
  if ([...source.matchAll(/\.promising\?\.\(/g)].length !== count) {
    throw drift("expected every promising reference to be an optional call");
  }
  return source;
}

/** Writes generated files under outDir; a name that resolves outside it is refused. */
export function writeFiles(outDir, files) {
  const base = resolve(outDir);
  for (const [file, bytes] of Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1))) {
    const dest = resolve(base, file);
    if (!dest.startsWith(base + sep)) throw new Error(`generated file escapes the output directory: ${file}`);
    mkdirSync(join(dest, ".."), { recursive: true });
    writeFileSync(dest, bytes);
  }
}

// wit-component adds a few tiny core modules (`<name>.coreN.wasm`: the destructor table of the resources and
// its fixups). They carry no logic of their own, so their bytes go into `<name>.shims.js` and the files are
// removed: the package then holds exactly one .wasm per component (gate G5) and a loader only has to fetch
// that one.
function embedShims(outDir, name) {
  const shims = readdirSync(outDir).filter((f) => /\.core\d+\.wasm$/.test(f)).sort();
  if (shims.length === 0) return;
  const lines = shims.map((f) => {
    const bytes = readFileSync(join(outDir, f));
    if (bytes.length > 1024) throw new Error(`${f} is too large to be a shim (${bytes.length} bytes)`);
    return `  "${f}": Uint8Array.of(${[...bytes].join(", ")}),`;
  });
  writeFileSync(join(outDir, `${name}.shims.js`), `// Generated by tools/transpile.mjs: bytes of the wit-component shim modules of ${name}.\nexport const shims = {\n${lines.join("\n")}\n};\n`);
  for (const f of shims) rmSync(join(outDir, f));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [component, out] = process.argv.slice(2);
  if (!component || !out) {
    console.error("usage: node tools/transpile.mjs <component.wasm> <out-dir>");
    process.exit(2);
  }
  const files = await transpileComponent(component, out);
  console.log(`transpiled ${component} -> ${out}: ${files.join(", ")}`);
}
